-- Dynamic production monitoring configuration.
-- Secrets are stored in Supabase Vault and are only exposed through
-- service-role-only SECURITY DEFINER functions used by Edge Functions.

CREATE TABLE IF NOT EXISTS public.monitoring_settings (
  environment text PRIMARY KEY DEFAULT 'production'
    CHECK (environment = 'production'),
  enabled boolean NOT NULL DEFAULT false,
  minimum_severity text NOT NULL DEFAULT 'p1'
    CHECK (minimum_severity IN ('p1', 'p2', 'p3')),
  send_recovery boolean NOT NULL DEFAULT true,
  telegram_bot_secret_id uuid,
  telegram_chat_secret_id uuid,
  webhook_secret_id uuid,
  bot_username text,
  last_test_at timestamptz,
  last_test_success boolean,
  last_test_message text,
  updated_by text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.monitoring_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor text NOT NULL,
  action text NOT NULL,
  success boolean NOT NULL DEFAULT true,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.monitoring_incidents (
  fingerprint text PRIMARY KEY,
  monitor_name text NOT NULL,
  severity text NOT NULL CHECK (severity IN ('p1', 'p2', 'p3')),
  status text NOT NULL CHECK (status IN ('open', 'recovered')),
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  recovered_at timestamptz,
  occurrence_count integer NOT NULL DEFAULT 1 CHECK (occurrence_count > 0),
  last_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  telegram_open_sent boolean NOT NULL DEFAULT false,
  telegram_recovery_sent boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.monitoring_alert_nonces (
  nonce text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS monitoring_audit_logs_created_at_idx
  ON public.monitoring_audit_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS monitoring_audit_logs_actor_action_idx
  ON public.monitoring_audit_logs (actor, action, created_at DESC);
CREATE INDEX IF NOT EXISTS monitoring_incidents_status_idx
  ON public.monitoring_incidents (status, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS monitoring_alert_nonces_created_at_idx
  ON public.monitoring_alert_nonces (created_at);

